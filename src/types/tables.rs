/// The known name of a HUD item id: a gun, ability or gadget.
pub fn item_name(id: u64) -> Option<&'static str> {
    ITEMS.iter().find(|i| i.0 == id).map(|i| i.1)
}

/// What kind of item a HUD item id is, when known.
pub fn item_kind(id: u64) -> Option<ItemKind> {
    ITEMS.iter().find(|i| i.0 == id).map(|i| i.2)
}

/// What is known about a weapon attachment id.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct AttachmentInfo {
    pub name: Option<&'static str>,
    /// The name is inferred from id order and shared skins, not read.
    pub inferred: bool,
    /// For sights: whether the sight magnifies, when known.
    pub magnified: Option<bool>,
}

/// What the lookup table knows about a weapon attachment id.
pub fn attachment_info(id: u64) -> AttachmentInfo {
    ATTACHMENTS
        .iter()
        .find(|a| a.0 == id)
        .map(|a| AttachmentInfo {
            name: a.1,
            inferred: a.2,
            magnified: a.3,
        })
        .unwrap_or_default()
}
