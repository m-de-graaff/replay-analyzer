//! Names of gadget objects (Y11S3), for [`crate::gadgets`]: by the asset
//! of the entity, and by the type index its component states.
//!
//! Both tables were built from 10 test rounds and 34 real rounds. A row
//! of [`GADGET_ASSETS`] that is not `inferred` has the name of the
//! loadout slot whose asset the object's is, as a body of some round
//! carried it. An `inferred` row is an object no slot holds (what a
//! launcher fires, what another object leaves behind), named after the
//! only operator it was seen with.

use crate::throws::Slot;

/// What an asset is.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct GadgetAsset {
    pub asset: u64,
    pub name: &'static str,
    /// The loadout slot the object is from, when a body carries it.
    pub slot: Option<Slot>,
    /// Named by this table's makers, not by a loadout slot.
    pub inferred: bool,
    /// The asset of the thrown object that leaves this one behind.
    pub parent: Option<u64>,
}

const fn row(
    asset: u64,
    name: &'static str,
    slot: Option<Slot>,
    inferred: bool,
    parent: Option<u64>,
) -> GadgetAsset {
    GadgetAsset {
        asset,
        name,
        slot,
        inferred,
        parent,
    }
}

