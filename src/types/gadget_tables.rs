/// The row of an asset.
pub(crate) fn gadget_asset(asset: u64) -> Option<&'static GadgetAsset> {
    let i = GADGET_ASSETS
        .binary_search_by_key(&asset, |r| r.asset)
        .ok()?;
    GADGET_ASSETS.get(i)
}

/// The name of a type index; `placed` says which component stated it.
pub(crate) fn gadget_type(placed: bool, index: u16) -> Option<&'static str> {
    let found = GADGET_TYPES.iter().find(|t| t.0 == placed && t.1 == index);
    found.map(|t| t.2)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_asset_table_is_sorted_and_finds_its_rows() {
        assert!(GADGET_ASSETS.windows(2).all(|w| w[0].asset < w[1].asset));
        let wire = gadget_asset(367839440370).unwrap();
        assert_eq!((wire.name, wire.slot), ("Barbed Wire", GADGET));
        let barrier = gadget_asset(375382544571).unwrap();
        assert!(barrier.inferred);
        assert_eq!(barrier.parent, Some(373332376744));
        assert_eq!(gadget_asset(1), None);
    }

    #[test]
    fn a_type_index_is_named_by_its_component() {
        assert_eq!(gadget_type(true, 206), Some("Barbed Wire"));
        assert_eq!(gadget_type(false, 206), None);
        assert_eq!(gadget_type(false, 100), Some("Frag Grenade"));
    }
}
